// Run with: node scripts/validate-finance.cjs
// No extra runner/dependencies: compile the pure TypeScript module in memory.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const ts = require('typescript');
const filename = require('node:path').resolve(__dirname, '../src/utils/financePeriod.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const mod = new Module(filename, module);
mod._compile(compiled.outputText, filename);
const { buildFinanceReport, financialOrderTotal, financeDateKey, financeBounds, matchesFinancePeriod, validateFinancePeriod, financePeriodLabel } = mod.exports;
const now = new Date('2026-01-01T15:00:00Z');
let checks = 0;
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };
check(financeDateKey('2026-01-01T02:59:59.999Z'), '2025-12-31');
check(financeDateKey('2026-01-01T03:00:00Z'), '2026-01-01');
check(financeDateKey('invalid'), '');
check(financeBounds('last30', now), { start: '2025-12-03', end: '2026-01-01' });
check(financeBounds('year', now), { start: '2026-01-01', end: '2026-01-01' });
check(financeBounds('month', now), { start: '2026-01-01', end: '2026-01-01' });
check(financeBounds('week', now), { start: '2025-12-28', end: '2026-01-01' });
const range = { type: 'range', start: '2025-12-31', end: '2026-01-01' };
check(matchesFinancePeriod('2025-12-31T02:59:59.999Z', range, now), false);
check(matchesFinancePeriod('2025-12-31T03:00:00Z', range, now), true);
check(matchesFinancePeriod('2026-01-02T02:59:59.999Z', range, now), true);
check(matchesFinancePeriod('2026-01-02T03:00:00Z', range, now), false);
const months = { type: 'months', months: ['2025-11', '2026-01'] };
check(matchesFinancePeriod('2025-11-15T15:00:00Z', months, now), true);
check(matchesFinancePeriod('2025-12-15T15:00:00Z', months, now), false);
check(matchesFinancePeriod('2026-01-15T15:00:00Z', months, now), true);
check(matchesFinancePeriod('2024-02-29T15:00:00Z', { type: 'day', day: '2024-02-29' }, now), true);
check(matchesFinancePeriod('2026-01-02T15:00:00Z', { type: 'preset', preset: 'year' }, now), false);
check(matchesFinancePeriod('2025-12-02T15:00:00Z', { type: 'preset', preset: 'last30' }, now), false);
check(matchesFinancePeriod('2025-12-03T15:00:00Z', { type: 'preset', preset: 'last30' }, now), true);
check(validateFinancePeriod({ type: 'day', day: '2026-02-29' }) !== null, true);
check(validateFinancePeriod({ type: 'range', start: '2026-02-01', end: '2026-01-01' }) !== null, true);
check(validateFinancePeriod({ type: 'range', start: '', end: '' }) !== null, true);
check(validateFinancePeriod({ type: 'months', months: [] }) !== null, true);
check(validateFinancePeriod({ type: 'months', months: ['2026-13'] }) !== null, true);
check(matchesFinancePeriod('invalid', { type: 'all' }), false);
check(matchesFinancePeriod('2020-01-01T15:00:00Z', { type: 'all' }), true);
check(financePeriodLabel(range), '31/12/2025 a 01/01/2026');
const order = (id, data, status, total, tipoEntrega = 'retirada') => ({ _id: id, data, status, total, tipoEntrega, itens: [{ preco: 10.1, quantidade: 2 }], endereco: { deliveryFee: 3.5 } });
const orders = [order('a', '2025-12-31T15:00:00Z', 'entregue', 25), order('b', '2026-01-01T15:00:00Z', 'entregue', 0, 'entrega'), order('c', '2026-01-01T15:00:00Z', 'cancelado', 100), order('d', '2026-01-01T15:00:00Z', 'preparando', 30), order('e', '2026-01-02T15:00:00Z', 'entregue', 1000)];
const report = buildFinanceReport(orders, range, now);
check(report.orders.length, 4);
check(report.completed, 2);
check(report.revenue, 48.7);
check(report.pendingOrders.map(order => order._id), ['d']);
check(financialOrderTotal(orders[0]), 25);
check(financialOrderTotal(orders[1]), 23.7);
check(financialOrderTotal({ ...orders[1], tipoEntrega: 'local' }), 20.2);
check(buildFinanceReport([order('f', '2026-01-01T15:00:00Z', 'entregue', 0.1), order('g', '2026-01-01T15:00:00Z', 'entregue', 0.2)], range, now).revenue, 0.3);
console.log(`${checks} verificações de período financeiro passaram.`);
